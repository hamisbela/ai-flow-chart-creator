import Together from 'together-ai';

const together = new Together({ 
    apiKey: import.meta.env.VITE_TOGETHER_API_KEY 
});

export async function generateImage(prompt) {
    try {
        const response = await together.images.create({
            model: "black-forest-labs/FLUX.1-schnell-Free",
            prompt: `professional flow chart diagram, clean and organized flowchart, ${prompt}, white background, clear arrows and connections, professional diagram layout, business process flow, clear text labels, organized chart structure, high resolution diagram`,
            width: 1024,
            height: 1024,
            steps: 4,
            n: 1,
            response_format: "b64_json"
        });
        
        return response.data[0].b64_json;
    } catch (error) {
        console.error('Error generating flow chart:', error);
        throw error;
    }
}